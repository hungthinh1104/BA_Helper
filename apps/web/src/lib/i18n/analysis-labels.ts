type WidenLabelShape<T> = T extends string
  ? string
  : T extends object
    ? { readonly [K in keyof T]: WidenLabelShape<T[K]> }
    : T

export type AnalysisWorkspaceLabels = WidenLabelShape<(typeof analysisWorkspaceLabels)["en"]>

export function getAnalysisWorkspaceLabels(
  locale: LocaleInput = DEFAULT_ANALYSIS_WORKSPACE_LOCALE,
): AnalysisWorkspaceLabels {
  const resolvedLocale = normalizeAppLocale(locale)
  if (resolvedLocale === "vi-VN") return analysisWorkspaceLabels["vi-VN"]
  if (resolvedLocale === "ja-JP") return analysisWorkspaceLabels["ja-JP"]
  return analysisWorkspaceLabels.en
}
